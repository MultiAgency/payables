import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { test, mock } from 'node:test';
import { createRouterClient } from '@orpc/server';
import { router } from '../src/router.js';
import { api } from '../src/api.js';
import { freshDirectory } from './fixtures/harness.js';
freshDirectory('setup-local-records');
test('retained records remain readable when provider-backed setup fails', async () => {
  delete process.env.TREASURY_ACCOUNT;
  mock.method(globalThis, 'fetch', async () => assert.fail('Unexpected network request'));
  mock.method(api, 'getAgent', async () => { throw new Error('Provider unavailable'); });
  mock.method(api, 'listGrants', async () => { throw new Error('Provider unavailable'); });
  mkdirSync('.ops', {recursive:true});
  mkdirSync('.owner-intents', {recursive:true});
  const opsFile = `.ops/${process.env.AGENT_ID}.jsonl`;
  const ops = JSON.stringify({idempotencyKey:'retained-operation',at:'2026-01-01T00:00:00Z',kind:'payout',method:'transfer',request:{asset:'usdc',amount:'1000000',recipient:'fixture.near',confidential:true}})+'\n';
  const ownersFile = '.owner-intents/.env.json';
  const owners = JSON.stringify({retainedOwner:{stage:'submitted',type:'approval_vote',expiresAt:'2020-01-01T00:00:00Z',signedData:{signature:'PRIVATE_FIXTURE'},paymentApproval:{correlationId:'retained-payment',verdict:'approve'}}});
  writeFileSync(opsFile,ops); writeFileSync(ownersFile,owners);
  const client = createRouterClient(router);
  await assert.rejects(client.setup());
  assert.equal((await client.activity()).length,1);
  assert.equal((await client.unresolved())[0]?.key,'retained-operation');
  const actions = await client.owner.actions();
  assert.equal(actions[0]?.correlationId,'retainedOwner');
  assert.equal(actions[0]?.stage,'submitted');
  assert.doesNotMatch(JSON.stringify(actions),/PRIVATE_FIXTURE/);
  assert.equal(readFileSync(opsFile,'utf8'),ops);
  assert.equal(readFileSync(ownersFile,'utf8'),owners);
});
